"""Main pipeline: run all five experiments in sequence and generate RESULTS.md."""
from __future__ import annotations

import sys
import time
import logging
import traceback
from pathlib import Path
from typing import Any

import matplotlib
matplotlib.use('Agg')

RESULTS_DIR = Path(__file__).parent / 'results'
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s %(levelname)s %(name)s  %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(RESULTS_DIR / 'pipeline.log', mode='w'),
    ],
)
logger = logging.getLogger('run_all')


# ---------------------------------------------------------------------------
# Helper: time an experiment block
# ---------------------------------------------------------------------------

def _run_step(name: str, fn) -> tuple[Any, float]:
    logger.info("=" * 60)
    logger.info("STARTING  %s", name)
    logger.info("=" * 60)
    t0 = time.perf_counter()
    try:
        result = fn()
        elapsed = time.perf_counter() - t0
        logger.info("FINISHED  %s  in %.1fs", name, elapsed)
        return result, elapsed
    except Exception:
        elapsed = time.perf_counter() - t0
        logger.error("FAILED    %s  after %.1fs:\n%s", name, elapsed, traceback.format_exc())
        return None, elapsed


