# ---------------------------------------------------------------------------
# RESULTS.md generator
# ---------------------------------------------------------------------------

def write_results_md(outcomes: dict) -> None:
    """Compile all experiment summaries into results/RESULTS.md."""
    import pandas as pd

    lines: list[str] = [
        "# RESULTS\n",
        "> Auto-generated by `run_all.py`.\n",
        "",
        "## Pipeline Summary\n",
        "| Experiment | Status | Runtime (s) |",
        "|-----------|--------|------------|",
    ]
    for name, info in outcomes.items():
        status = "✅ OK" if info.get('ok') else "❌ FAILED"
        lines.append(f"| {name} | {status} | {info.get('elapsed', 0):.1f} |")

    lines += ["", "---", ""]

    # ------------------------------------------------------------------ #
    # Exp 1: Descriptive stats                                             #
    # ------------------------------------------------------------------ #
    lines += ["## Exp 1 – Descriptive Characterisation\n"]
    stats_path = RESULTS_DIR / 'summary_statistics.csv'
    if stats_path.exists():
        df = pd.read_csv(stats_path, index_col=0)
        lines.append("### Summary Statistics (first 10 ETFs)\n")
        lines.append(df.head(10).to_markdown())
        lines.append("")
        mean_col = 'mean_daily' if 'mean_daily' in df.columns else 'mean'
        lines.append(
            f"**N assets:** {len(df)}  "
            f"| **Mean daily ret range:** {df[mean_col].min()*100:.3f}% – {df[mean_col].max()*100:.3f}%  "
            f"| **Avg excess kurtosis:** {df['excess_kurtosis'].mean():.2f}"
        )
    else:
        lines.append("_summary_statistics.csv not found._")

    lines += ["", "**Artifacts:** `correlation_heatmap.png`, `normalized_prices_by_category.png`, "
              "`cumulative_returns_by_category.png`, `return_distributions.png`", ""]

    # ------------------------------------------------------------------ #
    # Exp 2: Historical optimisation                                       #
    # ------------------------------------------------------------------ #
    lines += ["---", "", "## Exp 2 – Historical Rolling-Window Optimisation\n"]
    hist_path = RESULTS_DIR / 'exp2_metrics_gross.csv'
    if hist_path.exists():
        df = pd.read_csv(hist_path, index_col=0)
        lines.append("### Gross Performance Metrics\n")
        lines.append(df.round(4).to_markdown())
        lines.append("")
        lines.append(
            "**Key finding:** Conservative strategies (MVP, C95) tend to have lower "
            "volatility, smaller drawdowns, and comparable or higher risk-adjusted returns "
            "relative to BHP and tangent portfolios."
        )
    else:
        lines.append("_exp2_metrics_gross.csv not found._")
    lines.append("")
    lines.append("**Artifacts:** `exp2_cumulative_value.png`\n")

    # ------------------------------------------------------------------ #
    # Exp 3: Tail-risk diagnostics                                         #
    # ------------------------------------------------------------------ #
    lines += ["---", "", "## Exp 3 – Extreme-Value Tail Diagnostics\n"]
    tail_path = RESULTS_DIR / 'exp3_tail_metrics.csv'
    if tail_path.exists():
        df = pd.read_csv(tail_path, index_col=0)
        lines.append("### Tail-Risk Metrics\n")
        lines.append(df.round(4).to_markdown())
        lines.append("")
        lines.append(
            "**Key finding:** Optimised portfolios reduce VaR, CVaR, and MDD relative "
            "to BHP, but heavy tails remain; Hill tail-index estimates confirm "
            "power-law behaviour across all strategies."
        )
    else:
        lines.append("_exp3_tail_metrics.csv not found._")
    lines.append("")
    lines.append("**Artifacts:** `exp3_hill_curves.png`, `exp3_tail_comparison.png`\n")

    # ------------------------------------------------------------------ #
    # Exp 4: Dynamic optimisation                                          #
    # ------------------------------------------------------------------ #
    lines += ["---", "", "## Exp 4 – Dynamic ARMA-GARCH / Student-t Copula Optimisation\n"]
    lines.append(
        "**Assumptions logged:**\n"
        "- ARMA(1,1)-GARCH(1,1) marginal model (paper order unspecified)\n"
        "- Empirical PIT for marginal-to-uniform transformation\n"
        "- Student-t copula; degrees-of-freedom = median of univariate t-fits\n"
        "- 2 000 Monte Carlo scenarios per rebalancing date\n"
        "- Monthly rebalancing (every 21 trading days)\n"
        "- Variant A: no dynamic turnover cap (primary)\n"
    )
    dyn_path = RESULTS_DIR / 'exp4_metrics_varA.csv'
    if dyn_path.exists():
        df = pd.read_csv(dyn_path, index_col=0)
        lines.append("### Dynamic Strategy Gross Metrics\n")
        lines.append(df.round(4).to_markdown())
        lines.append("")
        lines.append(
            "**Key finding:** Dynamic predictive portfolios with conservative objectives "
            "(MVP, C95, C99, MCR95, MCR99) benefit from the conditional mean/covariance "
            "forecast, while TVP variants remain sensitive to return forecasting errors."
        )
    else:
        lines.append("_exp4_metrics_varA.csv not found._")
    lines.append("")
    lines.append("**Artifacts:** `exp4_cumulative_value.png`\n")

    # ------------------------------------------------------------------ #
    # Exp 5: Comparison + bootstrap                                        #
    # ------------------------------------------------------------------ #
    lines += ["---", "", "## Exp 5 – Historical vs Dynamic Comparison\n"]
    lines.append(
        "**Bootstrap settings:** block length = 20 trading days; "
        "B = 2 000 replications; 95 % CI.\n"
    )
    gross_path = RESULTS_DIR / 'exp5_gross_metrics.csv'
    if gross_path.exists():
        df = pd.read_csv(gross_path, index_col=0)
        lines.append("### Gross Sharpe / Calmar / STARR-95\n")
        lines.append(df.round(4).to_markdown())
        lines.append("")
    else:
        lines.append("_exp5_gross_metrics.csv not found._\n")

    boot_path = RESULTS_DIR / 'exp5_bootstrap_results.csv'
    if boot_path.exists():
        df = pd.read_csv(boot_path)
        lines.append("### Moving-Block Bootstrap Significance (DYN − HIST Sharpe)\n")
        lines.append(df.round(4).to_markdown(index=False))
        lines.append("")
        sig = df[df['is_significant']]['pair_metric'].tolist()
        lines.append(f"**Significant differences (CI excludes 0):** {sig or 'none'}\n")
    else:
        lines.append("_exp5_bootstrap_results.csv not found._\n")

    lines.append("**Artifacts:** `exp5_rolling_sharpe.png`, `exp5_cost_sensitivity.png`\n")

    # ------------------------------------------------------------------ #
    # Write file                                                           #
    # ------------------------------------------------------------------ #
    md_path = RESULTS_DIR / 'RESULTS.md'
    md_path.write_text('\n'.join(lines) + '\n')
    logger.info("RESULTS.md written → %s", md_path)


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------

def main() -> None:
    outcomes: dict[str, dict] = {}

    for name, fn in [
        ('Exp1_Descriptive', exp1),
        ('Exp2_Historical',  exp2),
        ('Exp3_TailRisk',    exp3),
        ('Exp4_Dynamic',     exp4),
        ('Exp5_Comparison',  exp5),
    ]:
        result, elapsed = _run_step(name, fn)
        outcomes[name] = {'ok': result is not None, 'elapsed': elapsed, 'result': result}

    write_results_md(outcomes)

    n_ok = sum(1 for v in outcomes.values() if v['ok'])
    logger.info("Pipeline complete: %d / %d experiments succeeded.", n_ok, len(outcomes))
    if n_ok < len(outcomes):
        sys.exit(1)


if __name__ == '__main__':
    main()
